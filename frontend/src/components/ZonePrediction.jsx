
import { getPredictionByZone } from '../data/predictionData'

function ZonePrediction({ selectedZone }) {
  if (!selectedZone) {
    return (
      <section className="zone-prediction-section">
        <h2>Zone-wise Prediction Details</h2>
        <p className="no-zone-selected">
          Select a farm zone on the map to view its illustrative prediction.
        </p>
      </section>
    )
  }

  const prediction = getPredictionByZone(selectedZone.id)

  if (!prediction) return null

  return (
    <section className="zone-prediction-section">
      <h2>Zone-wise Prediction Details</h2>

      <div className="zone-prediction-card">
        <div className="zone-prediction-header">
          <div>
            <p>Selected Zone</p>
            <h3>{selectedZone.name}</h3>
          </div>

          <span className={`risk-badge risk-${prediction.risk.toLowerCase()}`}>
            {prediction.risk} Risk
          </span>
        </div>

        <div className="zone-prediction-grid">
          <div>
            <p>Predicted Disease</p>
            <h4>{prediction.disease}</h4>
          </div>

          <div>
            <p>Illustrative Risk Score</p>
            <h4>{prediction.riskScore}%</h4>
          </div>

          <div>
            <p>Demo Confidence</p>
            <h4>{prediction.confidence}%</h4>
          </div>

          <div>
            <p>Illustrative Affected Area</p>
            <h4>{prediction.affectedArea} acres</h4>
          </div>
        </div>

        <p className="forecast-note">
          All prediction metrics above are synthetic demonstration values.
          They are not generated by a trained ML model.
        </p>
      </div>
    </section>
  )
}

export default ZonePrediction